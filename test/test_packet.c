/*
 * Host test: gcc -Wall -I. test/test_packet.c dxl_packet.c && ./a.out
 * Vectors are the examples from the ROBOTIS "DYNAMIXEL Protocol 2.0" e-Manual page.
 */
#include <assert.h>
#include <stdio.h>
#include <string.h>
#include "dxl_packet.h"

/* Passes a brace list through as one macro argument. */
#define B(...) {__VA_ARGS__}
/*
 * Builds (id, inst, params...) and compares against the manual's packet.
 * p[] has a leading 0 so an empty param list is still a valid array.
 */
#define CHECK_BUILD(expect, id, inst, ...) do {                         \
    const uint8_t e[] = expect, p[] = {0, __VA_ARGS__};                 \
    uint8_t out[64];                                                    \
    size_t n = dxl_build(out, sizeof out, id, inst, p + 1, sizeof p - 1); \
    assert(n == sizeof e && memcmp(out, e, n) == 0);                    \
} while (0)
#define HDR 0xFF, 0xFF, 0xFD, 0x00

static dxl_status_t parse(uint8_t *pkt, size_t n, bool stuffed) {
    dxl_status_t st;
    assert(dxl_parse(pkt, n, stuffed, &st) == DXL_OK);
    return st;
}

int main(void) {
    /* instruction packets */
    CHECK_BUILD(B(HDR, 0x01, 0x03, 0x00, 0x01, 0x19, 0x4E), 1, DXL_INST_PING);
    CHECK_BUILD(B(HDR, 0xFE, 0x03, 0x00, 0x01, 0x31, 0x42), DXL_BROADCAST, DXL_INST_PING);
    CHECK_BUILD(B(HDR, 0x01, 0x07, 0x00, 0x02, 0x84, 0x00, 0x04, 0x00, 0x1D, 0x15),
                1, DXL_INST_READ, 0x84, 0x00, 0x04, 0x00);
    CHECK_BUILD(B(HDR, 0x01, 0x09, 0x00, 0x03, 0x74, 0x00, 0x00, 0x02, 0x00, 0x00, 0xCA, 0x89),
                1, DXL_INST_WRITE, 0x74, 0x00, 0x00, 0x02, 0x00, 0x00);
    CHECK_BUILD(B(HDR, 0x01, 0x09, 0x00, 0x04, 0x68, 0x00, 0xC8, 0x00, 0x00, 0x00, 0xAE, 0x8E),
                1, DXL_INST_REG_WRITE, 0x68, 0x00, 0xC8, 0x00, 0x00, 0x00);
    CHECK_BUILD(B(HDR, 0x01, 0x03, 0x00, 0x05, 0x02, 0xCE), 1, DXL_INST_ACTION);
    CHECK_BUILD(B(HDR, 0x01, 0x04, 0x00, 0x06, 0x01, 0xA1, 0xE6), 1, DXL_INST_FACTORY_RESET, 0x01);
    CHECK_BUILD(B(HDR, 0x01, 0x03, 0x00, 0x08, 0x2F, 0x4E), 1, DXL_INST_REBOOT);
    CHECK_BUILD(B(HDR, 0x01, 0x08, 0x00, 0x10, 0x01, 0x44, 0x58, 0x4C, 0x22, 0xB1, 0xDC),
                1, DXL_INST_CLEAR, 0x01, 0x44, 0x58, 0x4C, 0x22);
    CHECK_BUILD(B(HDR, 0x01, 0x08, 0x00, 0x20, 0x01, 0x43, 0x54, 0x52, 0x4C, 0x16, 0xF5),
                1, DXL_INST_BACKUP, 0x01, 0x43, 0x54, 0x52, 0x4C);
    CHECK_BUILD(B(HDR, 0x01, 0x08, 0x00, 0x20, 0x02, 0x43, 0x54, 0x52, 0x4C, 0x9E, 0xF5),
                1, DXL_INST_BACKUP, 0x02, 0x43, 0x54, 0x52, 0x4C);
    CHECK_BUILD(B(HDR, 0xFE, 0x09, 0x00, 0x82, 0x84, 0x00, 0x04, 0x00, 0x01, 0x02, 0xCE, 0xFA),
                DXL_BROADCAST, DXL_INST_SYNC_READ, 0x84, 0x00, 0x04, 0x00, 0x01, 0x02);
    CHECK_BUILD(B(HDR, 0xFE, 0x11, 0x00, 0x83, 0x74, 0x00, 0x04, 0x00,
                  0x01, 0x96, 0x00, 0x00, 0x00, 0x02, 0xAA, 0x00, 0x00, 0x00, 0x82, 0x87),
                DXL_BROADCAST, DXL_INST_SYNC_WRITE, 0x74, 0x00, 0x04, 0x00,
                0x01, 0x96, 0x00, 0x00, 0x00, 0x02, 0xAA, 0x00, 0x00, 0x00);
    CHECK_BUILD(B(HDR, 0xFE, 0x0A, 0x00, 0x8A, 0x84, 0x00, 0x04, 0x00, 0x03, 0x07, 0x04, 0x20, 0xF2),
                DXL_BROADCAST, DXL_INST_FAST_SYNC_READ, 0x84, 0x00, 0x04, 0x00, 0x03, 0x07, 0x04);
    CHECK_BUILD(B(HDR, 0xFE, 0x0D, 0x00, 0x92, 0x01, 0x90, 0x00, 0x02, 0x00,
                  0x02, 0x92, 0x00, 0x01, 0x00, 0x1A, 0x05),
                DXL_BROADCAST, DXL_INST_BULK_READ, 0x01, 0x90, 0x00, 0x02, 0x00,
                0x02, 0x92, 0x00, 0x01, 0x00);
    CHECK_BUILD(B(HDR, 0xFE, 0x10, 0x00, 0x93, 0x01, 0x20, 0x00, 0x02, 0x00, 0xA0, 0x00,
                  0x02, 0x1F, 0x00, 0x01, 0x00, 0x50, 0xB7, 0x68),
                DXL_BROADCAST, DXL_INST_BULK_WRITE, 0x01, 0x20, 0x00, 0x02, 0x00, 0xA0, 0x00,
                0x02, 0x1F, 0x00, 0x01, 0x00, 0x50);
    CHECK_BUILD(B(HDR, 0xFE, 0x12, 0x00, 0x9A, 0x03, 0x84, 0x00, 0x04, 0x00, 0x07, 0x7C, 0x00,
                  0x02, 0x00, 0x04, 0x92, 0x00, 0x01, 0x00, 0xDA, 0x2D),
                DXL_BROADCAST, DXL_INST_FAST_BULK_READ, 0x03, 0x84, 0x00, 0x04, 0x00,
                0x07, 0x7C, 0x00, 0x02, 0x00, 0x04, 0x92, 0x00, 0x01, 0x00);

    /* status packets */
    uint8_t ping[] = {HDR, 0x01, 0x07, 0x00, 0x55, 0x00, 0x06, 0x04, 0x26, 0x65, 0x5D};
    dxl_status_t st = parse(ping, sizeof ping, true);
    assert(st.id == 1 && st.err == 0 && st.n == 3);
    assert((st.params[0] | st.params[1] << 8) == 1030 && st.params[2] == 0x26);
    uint8_t ping2[] = {HDR, 0x02, 0x07, 0x00, 0x55, 0x00, 0x06, 0x04, 0x26, 0x6F, 0x6D};
    assert(parse(ping2, sizeof ping2, true).id == 2);
    uint8_t read[] = {HDR, 0x01, 0x08, 0x00, 0x55, 0x00, 0xA6, 0x00, 0x00, 0x00, 0x8C, 0xC0};
    st = parse(read, sizeof read, true);
    assert(st.n == 4 && st.params[0] == 0xA6);
    uint8_t ack[] = {HDR, 0x01, 0x04, 0x00, 0x55, 0x00, 0xA1, 0x0C};
    assert(parse(ack, sizeof ack, true).n == 0);
    uint8_t sync2[] = {HDR, 0x02, 0x08, 0x00, 0x55, 0x00, 0x1F, 0x08, 0x00, 0x00, 0xBA, 0xBE};
    st = parse(sync2, sizeof sync2, true);
    assert(st.id == 2 && (st.params[0] | st.params[1] << 8) == 2079);
    uint8_t bulk1[] = {HDR, 0x01, 0x06, 0x00, 0x55, 0x00, 0x77, 0x00, 0xC3, 0x69};
    assert(parse(bulk1, sizeof bulk1, true).params[0] == 119);
    uint8_t bulk2[] = {HDR, 0x02, 0x05, 0x00, 0x55, 0x00, 0x24, 0x8B, 0xA9};
    assert(parse(bulk2, sizeof bulk2, true).params[0] == 36);
    read[10] ^= 1;
    assert(dxl_parse(read, sizeof read, true, &st) == DXL_ERR_CRC);

    /* fast sync read: IDs 3, 7, 4, Present Position (4 bytes) = 166, 2079, 1023 */
    uint8_t fsr[] = {HDR, 0xFE, 0x19, 0x00, 0x55, 0x00, 0x03, 0xA6, 0x00, 0x00, 0x00, 0x84, 0x08,
                     0x00, 0x07, 0x1F, 0x08, 0x00, 0x00, 0x16, 0xCA,
                     0x00, 0x04, 0xFF, 0x03, 0x00, 0x00, 0xD1, 0x9E};
    st = parse(fsr, sizeof fsr, false);
    assert(st.id == DXL_BROADCAST);
    const uint8_t ids[] = {3, 7, 4};
    const int pos[] = {166, 2079, 1023};
    size_t off = 0;
    const uint8_t *d;
    uint8_t err;
    for (int i = 0; i < 3; i++) {
        assert(dxl_fast_next(&st, &off, ids[i], 4, &err, &d) == DXL_OK && err == 0);
        assert((d[0] | d[1] << 8) == pos[i]);
    }
    assert(dxl_fast_next(&st, &off, 5, 4, &err, &d) == DXL_ERR_PACKET); /* ran off the end */
    off = 0;
    assert(dxl_fast_next(&st, &off, 9, 4, &err, &d) == DXL_ERR_PACKET); /* wrong id */

    /* fast bulk read: ID3 position 166 (4), ID7 PWM 421 (2), ID4 temperature 31 (1) */
    uint8_t fbr[] = {HDR, 0xFE, 0x14, 0x00, 0x55, 0x00, 0x03, 0xA6, 0x00, 0x00, 0x00, 0x67, 0xA4,
                     0x00, 0x07, 0xA5, 0x01, 0x24, 0x74,
                     0x00, 0x04, 0x1F, 0xD9, 0xC1};
    st = parse(fbr, sizeof fbr, false);
    off = 0;
    assert(dxl_fast_next(&st, &off, 3, 4, &err, &d) == DXL_OK && d[0] == 0xA6);
    assert(dxl_fast_next(&st, &off, 7, 2, &err, &d) == DXL_OK && (d[0] | d[1] << 8) == 421);
    assert(dxl_fast_next(&st, &off, 4, 1, &err, &d) == DXL_OK && d[0] == 31);
    fbr[16] = 0x87; /* second servo reports an access error + alert; re-CRC */
    fbr[sizeof fbr - 2] = 0, fbr[sizeof fbr - 1] = 0;
    uint16_t crc = dxl_crc(fbr, sizeof fbr - 2);
    fbr[sizeof fbr - 2] = crc & 0xFF, fbr[sizeof fbr - 1] = crc >> 8;
    st = parse(fbr, sizeof fbr, false);
    off = 0;
    assert(dxl_fast_next(&st, &off, 3, 4, &err, &d) == DXL_OK && err == 0);
    assert(dxl_fast_next(&st, &off, 7, 2, &err, &d) == DXL_OK && err == 0x87);
    assert(dxl_fast_next(&st, &off, 4, 1, &err, &d) == DXL_OK && d[0] == 31); /* others still readable */

    /* byte stuffing round trip: build a "status" whose first param is the err byte */
    uint8_t out[64];
    const uint8_t p[] = {0x00, 0xFF, 0xFF, 0xFD, 0x12};
    size_t n = dxl_build(out, sizeof out, 7, DXL_INST_STATUS, p, sizeof p);
    assert(n == 10 + sizeof p + 1); /* one stuffing byte */
    assert(out[11] == 0xFD && out[12] == 0xFD);
    st = parse(out, n, true);
    assert(st.id == 7 && st.n == 4 && memcmp(st.params, p + 1, 4) == 0);

    assert(dxl_build(out, 12, 1, DXL_INST_WRITE, p, sizeof p) == 0); /* too small */
    puts("ok");
    return 0;
}
